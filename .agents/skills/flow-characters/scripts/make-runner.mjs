#!/usr/bin/env node
// flow-characters step 1: write the in-page runner that builds saved Characters in Google Flow.
//
//   node .agents/skills/flow-characters/scripts/make-runner.mjs prompts/<film>-storyboard.md [--only "Gombu Tortoise,Meadow Mouse"] [--yetis] [--out file.js]
//
// It runs the Flow Account Seeder's own build (tools/flow-account-seeder/seed.mjs build <storyboard>) to get each
// Character's name, Character info, images, and voice (the storyboard's Voice cast, checked against voices.md),
// then copies the extension's own functions out of tools/flow-account-seeder/content.js (its DOM helpers, the
// Characters view, the image picker, the voice picker, setCharacterName, createCharacter) into one script that
// an agent pastes into the Flow tab with its browser tool. Browser-automation tools cannot open the extension's
// side panel, so the runner does the panel's Import step for Characters inside the page instead. Story cast only
// by default (the Yetis already exist); --yetis includes them.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";

const HERE = path.dirname(new URL(import.meta.url).pathname);
const ROOT = path.resolve(HERE, "../../../..");
const argv = process.argv.slice(2);
const opt = k => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : undefined; };
const storyboard = argv.find(a => a.endsWith(".md"));
if (!storyboard) { console.error("Usage: make-runner.mjs <storyboard.md> [--only \"Name,Name\"] [--yetis] [--out file.js]"); process.exit(2); }

// ---- the seed: names, info, images, voices ----
execFileSync(process.execPath, [path.join(ROOT, "tools/flow-account-seeder/seed.mjs"), "build", storyboard], { cwd: ROOT, stdio: ["ignore", "ignore", "inherit"] });
const stem = path.basename(storyboard, ".md");
const seedDir = path.join(ROOT, "references/flow-seed", stem);
const manifest = JSON.parse(fs.readFileSync(path.join(seedDir, "manifest.json"), "utf8"));
const only = opt("--only") ? new Set(opt("--only").split(",").map(s => s.trim().toLowerCase())) : null;
let chars = manifest.characters.filter(c => (argv.includes("--yetis") || c.kind !== "yeti") && (!only || only.has(c.name.toLowerCase())));
if (!chars.length) { console.error("No Characters to build (story cast only by default; --yetis adds the Yetis)."); process.exit(1); }

// ---- the extension's own code ----
const { pageCode } = await import(path.join(ROOT, "tools/flow-account-seeder/extract.mjs"));
const NAMES = ["dropFiles", "tileName", "imageTiles", "openImagesView", "collectImages", "openCharactersView", "characterTiles", "listCharacters", "findCharacterTile", "openCharacter",
  "slotChip", "slotImage", "pickFromProject", "cap", "currentVoice", "setVoice", "setCharacterVoice", "setCharacterName", "createCharacter"];
const body = pageCode(NAMES);

const jobs = chars.map(c => ({
  name: c.name, info: c.info || "", voice: c.voice || null,
  front: c.front ? path.basename(c.front) : null, turnaround: c.turnaround ? path.basename(c.turnaround) : null,
  frontPath: c.front ? path.join(seedDir, c.front) : null, turnaroundPath: c.turnaround ? path.join(seedDir, c.turnaround) : null,
}));
const missing = jobs.filter(j => !j.front || !j.turnaround);

const runner = `// flow-characters runner for ${stem}. Generated by make-runner.mjs from tools/flow-account-seeder/content.js.
(() => {
${body}

// Images: which of these names the open project already has, read from its Images view (the extension's own scan).
const haveImages = async (names) => { await openImagesView(); const want = names.map(n => n.toLowerCase()); const found = await collectImages(n => want.includes(n.toLowerCase())); return { have: [...found.keys()], missing: names.filter(n => ![...found.keys()].some(k => k.toLowerCase() === n.toLowerCase())) }; };
// Upload: an agent with a file-upload tool fills this input; its files are dropped onto the project grid,
// as the extension's Import does (Flow's own Upload button needs a real click).
const armUpload = () => {
  let input = document.getElementById("fas-upload");
  if (!input) {
    input = Object.assign(document.createElement("input"), { type: "file", id: "fas-upload", multiple: true, accept: "image/*" });
    input.setAttribute("aria-label", "flow-characters upload");
    Object.assign(input.style, { position: "fixed", top: "8px", left: "8px", zIndex: 99999 });
    input.addEventListener("change", async () => { const files = [...input.files]; window.__fasLog.push("dropping " + files.map(f => f.name).join(", ")); await dropFiles(files.map(f => ({ name: f.name, dataUrl: URL.createObjectURL(f), type: f.type }))); input.remove(); });
    document.body.appendChild(input);
  }
  return "upload input ready (aria-label: flow-characters upload)";
};
// dropFiles reads each file through toFile(); provide it for page-made object URLs.
async function toFile(f) { const blob = await (await fetch(f.dataUrl)).blob(); return new File([blob], f.name, { type: f.type || blob.type }); }

window.__fas = { createCharacter, listCharacters, haveImages, armUpload };
})();
window.__fasLog = [];
window.__fasJobs = ${JSON.stringify(jobs.map(({ frontPath, turnaroundPath, ...j }) => j))};
window.__fasState = { status: "idle", done: [], errors: [] };
window.__fasRun = async () => {
  const st = window.__fasState; st.status = "running";
  for (const j of window.__fasJobs) {
    if (st.done.includes(j.name)) continue;
    st.current = j.name;
    try { const r = await window.__fas.createCharacter(j); st.done.push(j.name); window.__fasLog.push("RESULT " + j.name + ": " + JSON.stringify(r)); }
    catch (e) { st.errors.push(j.name + ": " + e.message); st.status = "stopped at " + j.name; st.current = null; return; }
  }
  st.status = "done"; st.current = null;
};
window.__fasWait = async (s = 35) => { const t = Date.now(); while (window.__fasState.status === "running" && Date.now() - t < s * 1000) await new Promise(r => setTimeout(r, 500)); return { ...window.__fasState, log: window.__fasLog.slice(-8) }; };
"flow-characters runner ready: " + window.__fasJobs.map(j => j.name).join(", ");
`;
const out = opt("--out") || path.join(os.tmpdir(), `flow-characters-${stem}.js`);
fs.writeFileSync(out, runner);
execFileSync(process.execPath, ["--check", out]);

console.log(`Storyboard: ${storyboard}`);
console.log(`Characters to build: ${jobs.length}`);
for (const j of jobs) console.log(`  ${j.name.padEnd(20)} voice ${(j.voice || "none").padEnd(13)} ${j.front || "NO FRONT"} / ${j.turnaround || "NO TURNAROUND"}`);
if (missing.length) console.log(`Missing images (run /create-flow-assets first, or build without a Body): ${missing.map(j => j.name).join(", ")}`);
console.log(`Image files to upload if Flow lacks them:\n${jobs.flatMap(j => [j.frontPath, j.turnaroundPath]).filter(Boolean).map(p => "  " + p).join("\n")}`);
console.log(`Runner: ${out} (${runner.length} characters)`);
