#!/usr/bin/env node
// flow-agent-setup step 1: write the in-page runner that sets up a film's Flow project for the Agent.
//
//   node .agents/skills/flow-agent-setup/scripts/make-runner.mjs prompts/<film>-storyboard.md [--skip plates,memory,agent,view] [--out file.js]
//
// It runs the Flow Account Seeder's build (tools/flow-account-seeder/seed.mjs build <storyboard>) for the
// storyboard's plates (name and image file), its three Agent instruction cards (title, text, reference plate),
// and the project settings (Confirm before generating, Image and Video defaults in the film's orientation, and
// the View settings), then copies the extension's own functions out of its content.js into one script for the
// Flow tab. The runner, in order: renames each plate already in the project under its file name
// (plate-<location>.png) to its storyboard name (Plate - <Location>); adds each card as a Memory in Agent
// settings with its reference plate; sets the Agent settings; sets the View settings. Anything already in
// place is left as it is.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";

// fileURLToPath, not URL.pathname: on Windows the pathname is "/C:/...", which resolves to "C:\C:\...".
const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "../../../..");
const argv = process.argv.slice(2);
const opt = k => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : undefined; };
const storyboard = argv.find(a => a.endsWith(".md"));
if (!storyboard) { console.error("Usage: make-runner.mjs <storyboard.md> [--skip plates,memory,agent,view] [--out file.js]"); process.exit(2); }
const skip = new Set((opt("--skip") || "").split(",").map(s => s.trim()).filter(Boolean));

execFileSync(process.execPath, [path.join(ROOT, "tools/flow-account-seeder/seed.mjs"), "build", storyboard], { cwd: ROOT, stdio: ["ignore", "ignore", "inherit"] });
const stem = path.basename(storyboard, ".md");
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, "references/flow-seed", stem, "manifest.json"), "utf8"));
const title = manifest.title.replace(/\s+\d+\s*s\s+Storyboard\b.*$/i, "").replace(/\s+Storyboard\b.*$/i, "").trim();
// Names a plate can have in Flow before it is named: the repo's file name (plate-rhododendron-glade.png, as
// /create-flow-assets saves it, with or without the extension) and the seed's copy (Plate - Rhododendron Glade.png).
const kebab = s => s.toLowerCase().replace(/['’]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const plates = manifest.plates.map(p => {
  const k = kebab(p.name);
  const seedFile = p.image ? path.basename(p.image) : null;
  return { name: p.name, file: `${k}.png`, also: [...new Set([`${k}.png`, k, `${k}.jpg`, seedFile, seedFile && seedFile.replace(/\.[a-z]+$/i, "")].filter(Boolean))] };
});
const cards = manifest.instructions.map(c => ({ title: c.title, text: c.text, reference: c.reference || null }));
const settings = manifest.settings;
if (!settings) throw new Error("The seed has no settings: update tools/flow-account-seeder/seed.mjs.");

const { pageCode } = await import(pathToFileURL(path.join(ROOT, "tools/flow-account-seeder/extract.mjs")).href);
const NAMES = ["openImagesView", "tileName", "imageTiles", "assetId", "collectImages", "renameTile",
  "agentSettingsBtn", "inAgentSettings", "openAgentSettings", "memoryCard", "memoryCards", "listMemories",
  "pickMemoryReference", "fillMemories", "setDefaultsPage", "applyAgentSettings", "applyViewSettings"];

const runner = `// flow-agent-setup runner for ${stem}. Generated by make-runner.mjs from tools/flow-account-seeder/content.js.
(() => {
${pageCode(NAMES)}

// A plate in the project under its file name (plate-<location>.png) gets its storyboard name.
async function namePlates(plates) {
  await openImagesView();
  const out = [];
  for (const p of plates) {
    const names = [p.name, ...p.also].map(low);
    const have = await collectImages((n) => names.includes(low(n)));
    const found = [...have.keys()];
    if (found.some((n) => n === p.name)) { log(\`\${p.name}: already named.\`); out.push({ name: p.name, state: "named" }); continue; }
    if (!found.length) { log(\`\${p.name}: not in this project; upload \${p.file} first.\`, "warn"); out.push({ name: p.name, state: "missing" }); continue; }
    scrollAll(0); await sleep(400);
    let t = null;
    for (let i = 0; i < 40 && !t; i++) { t = imageTiles().find((x) => tileName(x) === found[0]); if (!t) { scrollAll(1); await sleep(300); } }
    if (!t) throw new Error(\`Could not find the tile "\${found[0]}".\`);
    await renameTile(t, p.name);
    log(\`\${found[0]} renamed to "\${p.name}".\`);
    out.push({ name: p.name, state: "renamed", from: found[0] });
  }
  return out;
}

window.__fas = { namePlates, fillMemories, listMemories, applyAgentSettings, applyViewSettings, projectName };
})();
window.__fasLog = [];
window.__fasSetup = ${JSON.stringify({ title, plates, cards, settings, skip: [...skip] })};
window.__fasState = { status: "idle", done: [], errors: [], results: {} };
window.__fasRun = async () => {
  const S = window.__fasSetup, st = window.__fasState; st.status = "running";
  const steps = [
    ["plates", () => window.__fas.namePlates(S.plates)],
    ["memory", () => window.__fas.fillMemories({ cards: S.cards })],
    ["agent", () => window.__fas.applyAgentSettings(S.settings.agent)],
    ["view", () => window.__fas.applyViewSettings(S.settings.view)],
  ];
  const here = window.__fas.projectName();
  if (here.toLowerCase() !== S.title.toLowerCase()) { st.errors.push(\`This tab is in "\${here}", not "\${S.title}". Open the film's project.\`); st.status = "wrong project"; return; }
  for (const [id, fn] of steps) {
    if (S.skip.includes(id) || st.done.includes(id)) continue;
    st.current = id;
    try { st.results[id] = await fn(); st.done.push(id); }
    catch (e) { st.errors.push(id + ": " + e.message); st.status = "stopped at " + id; st.current = null; return; }
  }
  st.status = "done"; st.current = null;
};
window.__fasWait = async (s = 35) => { const t = Date.now(); while (window.__fasState.status === "running" && Date.now() - t < s * 1000) await new Promise(r => setTimeout(r, 500)); return { ...window.__fasState, log: window.__fasLog.slice(-10) }; };
"flow-agent-setup runner ready: " + ${JSON.stringify(title)};
`;
const out = opt("--out") || path.join(os.tmpdir(), `flow-agent-setup-${stem}.js`);
fs.writeFileSync(out, runner);
execFileSync(process.execPath, ["--check", out]);

console.log(`Project: ${title}`);
console.log(`Plates:  ${plates.map(p => `${p.name} (renamed from ${p.file} if it is uploaded under that name)`).join(", ") || "none"}`);
console.log(`Memory:  ${cards.map(c => c.title + (c.reference ? ` [ref ${c.reference}]` : "")).join("; ")}`);
console.log(`Agent:   confirm ${settings.agent.confirm}; image ${settings.agent.image.model}, ${settings.agent.image.aspect}, x${settings.agent.image.outputs}; video ${settings.agent.video.model}, ${settings.agent.video.aspect}, x${settings.agent.video.outputs}`);
console.log(`View:    ${Object.entries(settings.view).map(([k, v]) => `${k} ${v === true ? "on" : v === false ? "off" : v}`).join(", ")}`);
if (skip.size) console.log(`Skipped: ${[...skip].join(", ")}`);
console.log(`Runner:  ${out} (${runner.length} characters)`);
